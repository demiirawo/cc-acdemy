// Function
// ============================================================================

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

serve(async (req: Request): Promise<Response> => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { recipientEmail, recipientName, subject, bodyHtml } = await req.json();

    if (!recipientEmail) {
      // A new starter was meant to get their welcome email and nobody has an
      // address for them — tell the admins rather than failing silently.
      await alertAdminsOfFailure(
        Deno.env.get("RESEND_API_KEY") ?? "",
        "Their welcome email to start joining Care Cuddle",
        `${(recipientName ?? "").trim() || "a new starter"} (no email address on file)`,
      );
      return new Response(JSON.stringify({ error: "recipientEmail is required" }), {
        status: 400,
        headers: { "Content-Type": "application/json", ...corsHeaders },
      });
    }

    const body =
      greeting(recipientName) +
      (bodyHtml ||
        paragraph("Welcome to Care Cuddle — your account is ready, and your first steps are waiting for you.") +
        paragraph("The button below takes you to your new starter checklist. It will guide you through everything, one step at a time, and you can ask for your offer letter and employment contract from there.")) +
      button("Open your new starter checklist", `${APP_URL}/view/hr?tab=onboarding`) +
      mutedParagraph(`If the button doesn't work, copy this link into your browser: ${APP_URL}/view/hr?tab=onboarding`);

    const html = emailShell(
      "Welcome to Care Cuddle",
      body,
      "You're receiving this because you're joining the team at Care Cuddle.",
    );

    const { error: sendError } = await resend.emails.send({
      from: EMAIL_SENDER,
      to: [recipientEmail],
      subject: subject || "Welcome to Care Cuddle — your first steps are ready",
      html,
    });

    if (sendError) {
      // The send failed, so the new starter heard nothing — alert the admins.
      await alertAdminsOfFailure(
        Deno.env.get("RESEND_API_KEY") ?? "",
        "Their welcome email to start joining Care Cuddle",
        `${(recipientName ?? "").trim() || "a new starter"} (email to ${recipientEmail} failed to send)`,
      );
      return new Response(JSON.stringify({ error: sendError.message || "Email failed to send" }), {
        status: 500,
        headers: { "Content-Type": "application/json", ...corsHeaders },
      });
    }

    return new Response(JSON.stringify({ success: true }), {
      status: 200,
      headers: { "Content-Type": "application/json", ...corsHeaders },
    });
  } catch (error) {
    const message = error instanceof Error ? error.message : "Unknown error";
    return new Response(JSON.stringify({ error: message }), {
      status: 500,
      headers: { "Content-Type": "application/json", ...corsHeaders },
    });
  }
});
